#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const webRoot = path.join(repoRoot, "web");
const viteBin = path.join(webRoot, "node_modules/vite/bin/vite.js");

const BUILTINS = [
  { key: "checkin", pluginId: "builtin.checkin", uiDir: path.join(repoRoot, "examples/plugins/checkin/ui") },
  { key: "boost", pluginId: "builtin.boost", uiDir: path.join(repoRoot, "examples/plugins/boost/ui") },
];

function mimeFor(relPath) {
  if (relPath.endsWith(".js") || relPath.endsWith(".mjs")) return "application/javascript";
  if (relPath.endsWith(".css")) return "text/css";
  if (relPath.endsWith(".json")) return "application/json";
  return "application/octet-stream";
}

function httpMimeFor(relPath) {
  if (relPath.endsWith(".js") || relPath.endsWith(".mjs")) {
    return "application/javascript; charset=utf-8";
  }
  if (relPath.endsWith(".css")) return "text/css; charset=utf-8";
  if (relPath.endsWith(".json")) return "application/json; charset=utf-8";
  return "application/octet-stream";
}

function walkFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkFiles(full));
    } else {
      out.push(full);
    }
  }
  return out;
}

const builtRecords = [];

for (const item of BUILTINS) {
  execFileSync(process.execPath, [viteBin, "build", "--config", "vite.config.mjs"], {
    cwd: item.uiDir,
    stdio: "inherit",
  });

  const distRoot = path.join(item.uiDir, "ui-dist");
  const uiSubdir = path.join(distRoot, "ui");
  if (!fs.existsSync(uiSubdir)) {
    throw new Error(`Expected built UI directory at ${uiSubdir}`);
  }

  for (const full of walkFiles(uiSubdir)) {
    if (full.endsWith(".html") || full.endsWith(".map")) {
      fs.unlinkSync(full);
    }
  }

  const assetFiles = walkFiles(uiSubdir)
    .map((full) => `ui/${path.relative(uiSubdir, full).replaceAll("\\", "/")}`)
    .filter((rel) => rel !== "ui/asset-manifest.json")
    .sort();

  const remoteEntryRel = "ui/assets/remoteEntry.js";
  if (!assetFiles.includes(remoteEntryRel)) {
    throw new Error(`Missing ${remoteEntryRel} in ${item.uiDir}`);
  }

  const manifestEntries = assetFiles.map((rel) => {
    const abs = path.join(distRoot, rel);
    const bytes = fs.readFileSync(abs);
    if (rel.endsWith(".js") || rel.endsWith(".mjs")) {
      const text = bytes.toString("utf8");
      if (text.includes("createInvalidHookError") || text.includes("react-dom.production")) {
        throw new Error(`Duplicate React runtime leaked into ${item.key}/${rel}`);
      }
    }
    return {
      path: rel,
      sha256: createHash("sha256").update(bytes).digest("hex"),
      size: bytes.length,
      content_type: mimeFor(rel),
    };
  });

  const manifestJson = JSON.stringify({ version: 1, files: manifestEntries }, null, 2) + "\n";
  fs.writeFileSync(path.join(uiSubdir, "asset-manifest.json"), manifestJson);
  fs.writeFileSync(path.join(item.uiDir, "asset-manifest.json"), manifestJson);

  builtRecords.push({
    ...item,
    assetFiles: [...assetFiles, "ui/asset-manifest.json"].sort(),
  });
}

const rustOut = path.join(repoRoot, "crates/api/src/plugins/ui_builtins_assets.rs");
const lines = [
  "// Auto-generated by scripts/build-builtin-plugin-uis.mjs. Do not edit manually.",
  "",
  "use super::boost::BUILTIN_BOOST_PLUGIN_ID;",
  "use super::builtins::BUILTIN_CHECKIN_PLUGIN_ID;",
  "",
  "pub(crate) fn builtin_asset_manifest_bytes(plugin_id: &str) -> Option<&'static [u8]> {",
  "    match plugin_id {",
  '        BUILTIN_CHECKIN_PLUGIN_ID => Some(include_bytes!("../../../../examples/plugins/checkin/ui/ui-dist/ui/asset-manifest.json")),',
  '        BUILTIN_BOOST_PLUGIN_ID => Some(include_bytes!("../../../../examples/plugins/boost/ui/ui-dist/ui/asset-manifest.json")),',
  "        _ => None,",
  "    }",
  "}",
  "",
  "type BuiltinUiAsset = (&'static str, &'static str, &'static [u8], &'static str);",
  "",
  "const BUILTIN_UI_ASSETS: &[BuiltinUiAsset] = &[",
];

for (const rec of builtRecords) {
  const constName =
    rec.pluginId === "builtin.checkin" ? "BUILTIN_CHECKIN_PLUGIN_ID" : "BUILTIN_BOOST_PLUGIN_ID";
  for (const rel of rec.assetFiles) {
    lines.push(
      `    (${constName}, ${JSON.stringify(rel)}, include_bytes!(${JSON.stringify(`../../../../examples/plugins/${rec.key}/ui/ui-dist/${rel}`)}), ${JSON.stringify(httpMimeFor(rel))}),`,
    );
  }
}

lines.push(
  "];",
  "",
  "pub(crate) fn lookup_builtin_ui_asset(",
  "    plugin_id: &str,",
  "    asset_path: &str,",
  ") -> Option<(&'static [u8], &'static str)> {",
  "    BUILTIN_UI_ASSETS",
  "        .iter()",
  "        .find_map(|&(pid, path, bytes, mime)| {",
  "            (pid == plugin_id && path == asset_path).then_some((bytes, mime))",
  "        })",
  "}",
  "",
);
fs.writeFileSync(rustOut, lines.join("\n"));
execFileSync("rustfmt", ["--edition", "2024", rustOut], { stdio: "inherit" });

for (const rec of builtRecords) {
  const manifestBytes = fs.readFileSync(
    path.join(rec.uiDir, "ui-dist/ui/asset-manifest.json"),
  );
  const bundleSha = createHash("sha256").update(manifestBytes).digest("hex");
  console.log(
    `[builtin-ui] ${rec.pluginId}: ${rec.assetFiles.length} assets, bundle_sha256=${bundleSha}`,
  );
}
